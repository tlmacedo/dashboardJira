-- Esquema base do Painel de Squads. Instantes em timestamptz; prazo (duedate) é data civil.

CREATE TABLE person (
    id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    jira_ref text    NOT NULL UNIQUE,
    name     text    NOT NULL,
    active   boolean NOT NULL DEFAULT true
);

CREATE TABLE issue (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key          text   NOT NULL UNIQUE,
    instance     text   NOT NULL,
    project      text   NOT NULL,
    issue_type   text,
    status       text,
    resolution   text,
    assignee_ref text,
    reporter_ref text,
    created      timestamptz,
    updated      timestamptz,
    resolved     timestamptz,
    duedate      date,
    labels       text[] NOT NULL DEFAULT '{}',
    parent_key   text,
    estimate_s   bigint,
    spent_s      bigint,
    raw          jsonb
);

CREATE TABLE change_event (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    changelog_id text        NOT NULL UNIQUE,
    issue_id     bigint      NOT NULL REFERENCES issue (id) ON DELETE CASCADE,
    field        text        NOT NULL,
    from_value   text,
    to_value     text,
    at           timestamptz NOT NULL,
    author_ref   text
);

CREATE TABLE worklog (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issue_id   bigint      NOT NULL REFERENCES issue (id) ON DELETE CASCADE,
    author_ref text,
    started    timestamptz NOT NULL,
    seconds    bigint      NOT NULL
);

CREATE TABLE sync_state (
    instance  text PRIMARY KEY,
    watermark timestamptz
);

CREATE TABLE access_log (
    id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id text        NOT NULL,
    route   text        NOT NULL,
    filters text,
    at      timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_change_event_issue_at ON change_event (issue_id, at);
CREATE INDEX idx_issue_status_resolved ON issue (status, resolved);
CREATE INDEX idx_worklog_started ON worklog (started);
