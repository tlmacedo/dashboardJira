-- Sincronização periódica (Plano 4A): estado por instância, histórico de execuções, id do Jira e
-- mapa de chaves de usuário. Só guarda códigos e contagens; nunca texto livre de erro.

ALTER TABLE sync_state
    ADD COLUMN ultima_reconciliacao timestamptz,
    ADD COLUMN suspensa_codigo      text,
    ADD COLUMN suspensa_em          timestamptz;

CREATE TABLE sync_run (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instance               text        NOT NULL,
    kind                   text        NOT NULL CHECK (kind IN ('INCREMENTAL', 'RECONCILIACAO', 'RETENCAO')),
    started_at             timestamptz NOT NULL,
    finished_at            timestamptz,
    status                 text        NOT NULL CHECK (status IN ('EM_ANDAMENTO', 'OK', 'FALHA', 'CANCELADA')),
    issues                 int         NOT NULL DEFAULT 0,
    eventos                int         NOT NULL DEFAULT 0,
    requisicoes            int         NOT NULL DEFAULT 0,
    incompletas            int         NOT NULL DEFAULT 0,
    usuarios_nao_resolvidos int        NOT NULL DEFAULT 0,
    removidas              int         NOT NULL DEFAULT 0,
    codigo_erro            text,
    http_status            int
);

CREATE INDEX idx_sync_run_instance_kind_started ON sync_run (instance, kind, started_at DESC);

ALTER TABLE issue
    ADD COLUMN jira_id     bigint,
    ADD COLUMN removida_em timestamptz;

CREATE UNIQUE INDEX uq_issue_instance_jira_id ON issue (instance, jira_id) WHERE jira_id IS NOT NULL;

CREATE TABLE jira_user_key (
    instance text        NOT NULL,
    user_key text        NOT NULL,
    username text        NOT NULL,
    visto_em timestamptz NOT NULL,
    PRIMARY KEY (instance, user_key)
);
